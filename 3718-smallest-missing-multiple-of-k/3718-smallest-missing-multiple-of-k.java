class Solution {
    public int missingMultiple(int[] nums, int k) {
        Map<Integer, Integer> map = new HashMap<>();
        for(int num : nums){
            map.put(num, map.getOrDefault(num, 0) + 1);
        }
        int smallest = k;
        while(map.containsKey(smallest)){
            smallest += k;
        }
        return smallest;
    }
}

